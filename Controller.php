class Controller extends \Piwik\Plugin\ControllerAdmin {

    private const NONCE_DUMP = 'DataExport.downloadDbDump';
    private const NONCE_UPLOAD = 'DataExport.handleDbUpload';
    private const NONCE_DELETE = 'DataExport.deleteFiles';

    public function index() {
        return $this->indexHome();
    }

    public function indexHome() {
        Piwik::checkUserHasSuperUserAccess();

        $downloadPreference = UserHelper::getUserPreference('downloadPreference', 'gzip');

        $dbConfig = \Piwik\Config::getInstance()->database;
        $dbName = $dbConfig['dbname'];
        $dbUser = $dbConfig['username'];
        $dbHost = $dbConfig['host'];

        $phpSettings = PHPHelper::getPhpSettings();
        $fileService = new FileService();
        $files = $fileService->getFilesInBackupDir();
        $settingsHelper = new SettingsHelper();
        $settings = $settingsHelper->getDataExportSettings();
        $dumpService = new DatabaseDumpService();
        $dumpMethod = $dumpService->getDumpMethodStatus();

        // Render the Twig template templates/index.twig and assign the view variable answerToLife to the view.
        return $this->renderTemplate(
            'index',
            array(
                'title' => Piwik::translate('DataExport_DataExport'),
                'import_title' => Piwik::translate('DataExport_ImportData'),
                'csv_title' => Piwik::translate('DataExport_CsvExport'),
                'downloadPreference' => $downloadPreference,
                'dbName' => $dbName,
                'dbUser' => $dbUser,
                'dbHost' => $dbHost,
                'phpSettings' => $phpSettings,
                'backupPath' => $settings['backupPath'],
                'files' => $files['files'],
                'totalFilesSize' => $files['size'],
                'clear_backups' => Piwik::translate('DataExport_ClearBackups'),
                'settings' => Piwik::translate('DataExport_Settings'),
                'autoDump' => 'none',
                'csvQuery' => $this->getCsvQueryExample(),
                'dumpMethod' => $dumpMethod,
                'backupJob' => $this->formatJobStatus((new BackupJobService())->getStatus()),
                'nonceDump' => Nonce::getNonce(self::NONCE_DUMP),
                'nonceUpload' => Nonce::getNonce(self::NONCE_UPLOAD),
                'nonceDelete' => Nonce::getNonce(self::NONCE_DELETE),
            )
        );
    }

    /**
     * The CSV export query as it runs, with the configured table prefix, for display.
     */
    private function getCsvQueryExample(): string {
        $sql = "SELECT <all columns of the joined tables, the first table wins on duplicate names>\n"
            . DatabaseDumpService::getSelectAllVisitsAndActionsFromSql();
        $sql = preg_replace('/\?/', '"2024-02-24 00:00:00"', $sql, 1);
        $sql = preg_replace('/\?/', '"2024-02-24 23:59:59"', $sql, 1);
        // Normalize indentation for display
        return preg_replace('/^\s+/m', '', $sql) . ';';
    }

    /**
     * Downloads a file from the backup folder.
     *
     * Only a file name is accepted, files outside the backup folder can't be
     * downloaded (e.g. ?file=../../config/config.ini.php).
     *
     * @throws \Exception If the file does not exist or is not readable.
     */
    public function downloadFile() {
        Piwik::checkUserHasSuperUserAccess();
        $fileService = new FileService();

        $fileName = Request::fromRequest()->getStringParameter('file', '');
        $filePath = $fileService->resolveBackupFile($fileName);

        if (!$filePath) {
            throw new \Exception("File does not exist or is not readable.");
        }

        $fileService->downloadFile($filePath);
    }

    /**
     * Sends a file generated by this plugin to the browser.
     */
    private function sendGeneratedFile(string $filePath) {
        if (!file_exists($filePath) || !is_readable($filePath)) {
            throw new \Exception("File does not exist or is not readable.");
        }
        $fileService = new FileService();
        $fileService->downloadFile($filePath);
    }

    /**
     * Downloads a DB dump
     */
    public function downloadDbDump() {
        Piwik::checkUserHasSuperUserAccess();
        // Not discarded on success: the page isn't reloaded after a download.
        if (!Nonce::verifyNonce(self::NONCE_DUMP, Request::fromPost()->getStringParameter('nonce', ''))) {
            throw new \Exception(Piwik::translate('General_ExceptionSecurityCheckFailed'));
        }

        // Correctly escape the user input
        $downloadPreference = !empty($_POST['download-preference']) ? htmlspecialchars($_POST['download-preference'], ENT_QUOTES, 'UTF-8') : 'none';

        UserHelper::setUserPreference('downloadPreference', $downloadPreference);

        try {
            $service = new DatabaseDumpService();
            $dumpPath = $service->generateDump($downloadPreference);

            $this->sendGeneratedFile($dumpPath);
        } catch (\Exception $e) {
            // Handle the error appropriately
            echo htmlspecialchars($e->getMessage(), ENT_QUOTES, 'UTF-8');
        }
    }

    /**
     * Starts a database backup in the background (see BackupJobService).
     * Large databases take longer than web server timeouts allow, so this
     * returns right away; the page polls backupStatus and downloads the
     * file when it is ready.
     */
    public function startDbDump() {
        Piwik::checkUserHasSuperUserAccess();
        if (!Nonce::verifyNonce(self::NONCE_DUMP, Request::fromPost()->getStringParameter('nonce', ''))) {
            throw new \Exception(Piwik::translate('General_ExceptionSecurityCheckFailed'));
        }

        $compression = Request::fromPost()->getStringParameter('download-preference', 'gzip');
        if (!BackupJobService::isValidCompression($compression)) {
            $compression = 'gzip';
        }
        UserHelper::setUserPreference('downloadPreference', $compression);

        $jobs = new BackupJobService();
        try {
            $detached = $jobs->start($compression);
            $response = ['ok' => true, 'status' => $this->formatJobStatus($jobs->getStatus())];
        } catch (\Exception $e) {
            $detached = true;
            $response = ['ok' => false, 'error' => $e->getMessage(), 'status' => $this->formatJobStatus($jobs->getStatus())];
        }

        $body = json_encode($response);
        if ($detached) {
            Common::sendHeader('Content-Type: application/json; charset=utf-8');
            return $body;
        }
        // No background process available: answer first, then dump in this process
        $jobs->respondAndRun($body);
        exit;
    }

    /**
     * Status of the backup started from this page, as JSON.
     */
    public function backupStatus() {
        Piwik::checkUserHasSuperUserAccess();
        Common::sendHeader('Content-Type: application/json; charset=utf-8');
        return json_encode($this->formatJobStatus((new BackupJobService())->getStatus()));
    }

    private function formatJobStatus(?array $status): ?array {
        if ($status === null) {
            return null;
        }
        $fileService = new FileService();
        $file = $status['file'] ?? null;
        $exists = $file && $fileService->resolveBackupFile($file);
        return [
            'state' => $status['state'],
            'startedAt' => date('Y-m-d H:i:s', (int) $status['startedAt']),
            'elapsed' => (int) (($status['finishedAt'] ?? time()) - $status['startedAt']),
            'file' => $exists ? $file : null,
            'size' => $exists ? $fileService->formatSize((int) ($status['size'] ?? 0)) : null,
            'downloadUrl' => $exists
                ? 'index.php?module=DataExport&action=downloadFile&file=' . rawurlencode($file)
                : null,
            'error' => $status['error'] ?? null,
        ];
    }

    public function handleDbUpload() {
        Piwik::checkUserHasSuperUserAccess();
        Nonce::checkNonce(self::NONCE_UPLOAD, Request::fromPost()->getStringParameter('nonce', ''));

        if (!empty($_FILES['dbDump']['name'])) {
            $uploadDir = PIWIK_USER_PATH . '/tmp/de_uploads/';
            if (!is_dir($uploadDir)) {
                mkdir($uploadDir, 0755, true);
            }

            $fileTmpPath = $_FILES['dbDump']['tmp_name'];
            $fileName = basename($_FILES['dbDump']['name']);
            $fileSize = $_FILES['dbDump']['size'];
            $fileType = $_FILES['dbDump']['type'];
            $error = $_FILES['dbDump']['error'];

            // Validate file (size, type, error status)
            if ($error > 0) {
                throw new \Exception("Error uploading file. Error code: $error.");
            }
            // if ($fileSize > 20971520) { // Example size limit: 20MB
            // Set to 1024MB
            if ($fileSize > 1073741824) {
                throw new \Exception("File size exceeds limit.");
            }
            if (!in_array($fileType, [
                'application/octet-stream',
                'application/sql',
                'text/plain',
                'application/gzip',
                'application/x-gzip',
            ])) {
                throw new \Exception("Invalid file type.");
            }
            if (!preg_match('/\.sql(\.gz)?$/i', $fileName)) {
                throw new \Exception("Invalid file extension, expected .sql or .sql.gz.");
            }

            $destPath = $uploadDir . $fileName;

            if (move_uploaded_file($fileTmpPath, $destPath)) {
                // Validate file content
                if (!$this->looksLikeSqlDump($destPath)) {
                    @unlink($destPath);
                    throw new \Exception("File does not appear to be a valid MySQL dump.");
                }
                $service = new DatabaseImportService();
                try {
                    $success = $service->importDump($destPath);
                } finally {
                    // Don't leave a full copy of the database lying around
                    @unlink($destPath);
                }
                if ($success) {
                    $notification = new Notification(Piwik::translate('DataExport_ImportSuccessMessage'));
                    $notification->context = Notification::CONTEXT_SUCCESS;
                    NotificationManager::notify('DataExport_ImportSuccess', $notification);
                    $url = Url::getCurrentQueryStringWithParametersModified([
                        'module' => 'DataExport',
                        'action' => 'index'
                    ]);
                    Url::redirectToUrl('index.php' . $url);
                }
            } else {
                throw new \Exception("Failed to move uploaded file.");
            }
        } else {
            throw new \Exception("No file uploaded.");
        }
    }

    /**
     * Checks the first lines for a mysqldump, mariadb-dump or DataExport PHP dump header.
     * MariaDB 11+ writes a "/*!999999\- enable the sandbox mode *\/" line first.
     */
    private function looksLikeSqlDump(string $path): bool {
        // gzopen() also reads uncompressed files
        $handle = @gzopen($path, 'rb');
        if (!$handle) {
            throw new \Exception("Unable to read uploaded file.");
        }
        try {
            for ($i = 0; $i < 5 && ($line = gzgets($handle)) !== false; $i++) {
                if (preg_match('/^-- (MariaDB|MySQL) dump \d+/', $line)
                    || strpos($line, \Piwik\Plugins\DataExport\Services\Dump\PhpSqlDumper::HEADER_SIGNATURE) === 0
                ) {
                    return true;
                }
            }
        } finally {
            gzclose($handle);
        }
        return false;
    }

    public function selectAllVisitsAndActions() {
        Piwik::checkUserHasSuperUserAccess();

        $siteId = Request::fromRequest()->getIntegerParameter('idSite', 0);

        // Because Matomo adds siteId to the URL, we need to check if it's for all sites
        $getAll = Request::fromRequest()->getIntegerParameter('getAll', 0);
        $siteId = $getAll !== 1 ? $siteId : 'all';

        $date = Request::fromPost()->getStringParameter('date', 'yesterday');
        if (!$date || $date == 'yesterday') {
            $date = Request::fromRequest()->getStringParameter('date', 'yesterday');
        }

        try {
            $service = new DatabaseDumpService();
            $dumpPath = $service->selectAllVisitsAndActions(null, $date, $siteId);
            if (!$dumpPath) {
                $notification = new Notification(Piwik::translate('DataExport_CsvEmptyMessage'));
                $notification->context = Notification::CONTEXT_WARNING;
                NotificationManager::notify('DataExport_CsvEmptyMessage', $notification);
                $url = Url::getCurrentQueryStringWithParametersModified([
                    'module' => 'DataExport',
                    'action' => 'index'
                ]);
                Url::redirectToUrl('index.php' . $url);
            }
            $this->sendGeneratedFile($dumpPath);
        } catch (\Exception $e) {
            // Handle the error appropriately
            echo htmlspecialchars($e->getMessage(), ENT_QUOTES, 'UTF-8');
        }
    }

    public function deleteFiles() {
        Piwik::checkUserHasSuperUserAccess();
        Nonce::checkNonce(self::NONCE_DELETE, Request::fromPost()->getStringParameter('nonce', ''));
        $files = Request::fromPost()->getArrayParameter('files', []);
        $service = new FileService();
        $service->deleteFiles($files);
        $notification = new Notification(Piwik::translate('DataExport_FilesDeletedMessage'));
        $notification->context = Notification::CONTEXT_SUCCESS;
        NotificationManager::notify('DataExport_FilesDeleted', $notification);
        return $this->indexHome();
    }
}
